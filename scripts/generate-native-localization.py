#!/usr/bin/env python3
"""Generate native resource tables from the reviewed English/Arabic copy catalog.

No network/API/translation service. --check validates content and compares every
expected generated file without modifying it. Source strings are presentation
keys only; protocol values and user/employer records are never rewritten.
"""
from pathlib import Path
import argparse,hashlib,json,re,sys,xml.etree.ElementTree as ET

ROOT=Path(__file__).resolve().parents[1]
PH=re.compile(r'\{([0-9]+)\}')

def android_text(value):
    # Android resource parsing treats unescaped apostrophes/quotes specially.
    return value.replace('\\','\\\\').replace("'","\\'").replace('"','\\"').replace('\n','\\n').replace('\r','\\r').replace('\t','\\t')

def kotlin_string(value):
    return json.dumps(value,ensure_ascii=False).replace('$','\\$')

def generate(catalog):
    assert isinstance(catalog,dict) and catalog.get('source_language')=='en' and catalog.get('target_language')=='ar'
    values=catalog['strings'];assert isinstance(values,dict) and values
    keys=sorted(values)
    ids={k:'c_'+hashlib.sha256(k.encode()).hexdigest()[:12] for k in keys}
    assert len(set(ids.values()))==len(keys),'Resource ID collision'
    for key in keys:
        ar=values[key]
        assert isinstance(ar,str) and ar.strip(),f'Empty Arabic: {key}'
        assert PH.findall(key)==sorted(PH.findall(key),key=int),f'Unordered source placeholders: {key}'
        numbers=[int(x) for x in PH.findall(key)]
        assert numbers==list(range(len(numbers))),f'Nonsequential/repeated source placeholders: {key}'
        assert sorted(PH.findall(key))==sorted(PH.findall(ar)),f'Placeholder mismatch: {key}'
        assert key.count('\n')==ar.count('\n'),f'Newline mismatch: {key}'
        if key.startswith(' '):assert ar.startswith(' '),f'Leading space mismatch: {key}'
        if key.endswith(' '):assert ar.endswith(' '),f'Trailing space mismatch: {key}'
    outputs={}
    for locale in ['en','ar']:
        lines=['/* Generated by scripts/generate-native-localization.py. Edit localization/native-copy.json. */']
        for key in keys:
            lines.append(json.dumps(key,ensure_ascii=False)+' = '+json.dumps(key if locale=='en' else values[key],ensure_ascii=False)+';')
        outputs[f'apple/AhmadCareer/{locale}.lproj/Localizable.strings']='\n'.join(lines)+'\n'
        tree=ET.Element('resources')
        for key in keys:
            node=ET.SubElement(tree,'string',name=ids[key],formatted='false')
            node.text='\"'+android_text(key if locale=='en' else values[key])+'\"'
        ET.indent(tree,space='    ')
        outputs[f'android/app/src/main/res/{"values" if locale=="en" else "values-ar"}/career_copy.xml']='<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated from localization/native-copy.json; do not edit by hand. -->\n'+ET.tostring(tree,encoding='unicode')+'\n'
    templates=[]
    for key in keys:
        numbers=PH.findall(key)
        if not numbers:continue
        parts=PH.split(key)[::2]
        # Adjacent placeholders cannot be recovered from an already rendered message.
        # Explicit UI template+args still supports them; fallback matching does not.
        if any(p=='' for p in parts[1:-1]) or len(''.join(parts))<6 or len(numbers)>12:continue
        templates.append({'key':key,'parts':parts,'arguments':len(numbers)})
    templates.sort(key=lambda x:(-sum(len(p) for p in x['parts']),x['key']))
    encoded=json.dumps(templates,ensure_ascii=False,indent=2)+'\n'
    outputs['apple/AhmadCareer/NativeCopyTemplates.json']=encoded
    outputs['android/app/src/main/res/raw/native_copy_templates.json']=encoded
    chunks=[keys[i:i+150] for i in range(0,len(keys),150)]
    kotlin=['package com.saleh.careerfinder','', '// Generated from localization/native-copy.json. Split initialization avoids JVM method-size limits.',
            'internal val nativeStringIds: Map<String, Int> by lazy {',
            '    buildMap {']
    kotlin += [f'        putAll(nativeCopyIds{i}())' for i in range(len(chunks))]
    kotlin+=['    }','}','']
    for i,chunk in enumerate(chunks):
        kotlin.append(f'private fun nativeCopyIds{i}(): Map<String, Int> = mapOf(')
        kotlin += ['    '+kotlin_string(key)+' to R.string.'+ids[key]+',' for key in chunk]
        kotlin+=[')','']
    outputs['android/app/src/main/java/com/saleh/careerfinder/NativeStringIds.kt']='\n'.join(kotlin)
    return outputs,templates

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    parser.add_argument('--catalog',type=Path,default=ROOT/'localization/native-copy.json')
    args=parser.parse_args()
    catalog=json.loads(args.catalog.read_text())
    outputs,templates=generate(catalog)
    mismatches=[]
    for name,content in outputs.items():
        path=ROOT/name
        if args.check:
            if not path.exists() or path.read_text()!=content:mismatches.append(name)
        else:
            path.parent.mkdir(parents=True,exist_ok=True);path.write_text(content)
    if mismatches:
        print(json.dumps({'ok':False,'out_of_date':mismatches},indent=2));return 1
    print(json.dumps({'ok':True,'mode':'check' if args.check else 'write','strings_per_language':len(catalog['strings']),'bounded_templates':len(templates),'files':list(outputs)},indent=2))
    return 0

if __name__=='__main__':sys.exit(main())
